#!/usr/bin/env python3
"""Build report.md tables from calls_classified.jsonl (written by analyze.py)."""
import collections
import glob
import json
import os
import re

OUT = os.path.join(os.environ["AUDIT_OUT"], "claude")
START, END = os.environ["AUDIT_START"], os.environ["AUDIT_END"]
ROOT = os.path.join(os.environ.get("WORKSPACE_ROOT") or os.path.expanduser("~"), ".claude/projects")

rows = [json.loads(l) for l in open(os.path.join(OUT, "calls_classified.jsonl"))]
stats = json.load(open(os.path.join(OUT, "stats.json")))


def tool_key(r):
    if r["server"]:
        return "MCP: " + r["server"]
    return r["tool"]


def is_naive_error(r):
    if r["tool"] == "Bash":
        return bool(r.get("is_error")) or (r.get("exit") not in (None, 0))
    return bool(r.get("is_error"))


def pct(a, b):
    return "%.1f%%" % (100.0 * a / b) if b else "-"


out = []
W = out.append

# ------------------------------------------------------------ scope
files = sorted(glob.glob(ROOT + "/*/**/*.jsonl", recursive=True))
sub_files = [f for f in files if "/subagents/" in f]
W("# Claude Code tool-call failure rates (%s to %s)" % (START, END))
W("")
W("Generated by `claude_analyze.py` and `claude_report.py` from `$WORKSPACE_ROOT/.claude/projects`. "
  "Every number below comes from `calls_classified.jsonl` in this directory.")
W("")
W("## Scope and method")
W("")
n_total = len(rows)
n_main = sum(1 for r in rows if r["tag"] == "main")
n_sub = sum(1 for r in rows if r["tag"] == "subagent")
resolved = [r for r in rows if r["category"] != "no_result"]
W("- Transcript files read: %d (%d under `*/subagents/`, tagged `subagent`)." % (len(files), len(sub_files)))
W("- Tool calls in window (dated %s through %s by the call's UTC timestamp): **%d** "
  "(%d main, %d subagent)." % (START, END, n_total, n_main, n_sub))
W("- Calls excluded because they fall outside the window: %d. Duplicate `tool_use` ids skipped "
  "(same call appearing in two files): %d." % (stats["excluded_out_of_window"], stats["duplicate_tool_use_ids_skipped"]))
W("- Calls with no recorded outcome: %d. Its result says the session ended before the call was recorded. "
  "Every in-window call has a `tool_result`. Rates use the %d other calls as denominator."
  % (n_total - len(resolved), len(resolved)))
W("- **Real failure** means the command or tool call did not do what it was meant to do, and the cause "
  "is not an expected exit code, a denial, or an interruption. See the category rules below.")
W("- **Naive error** is the count a plain `is_error` or non-zero-exit filter would give. It is shown "
  "for comparison only.")
W("- Categories: `ok`; `expected_nonzero` (grep/rg no match, diff differs, `test`/`[` false, probe "
  "such as `which` or `git check-ignore`, a test runner or linter reporting findings, `gh pr checks` "
  "reporting failing checks); `denied` (auto-mode classifier, hook or harness block, user rejection, "
  "MCP permission not granted); `interrupted`; `tool_misuse` (schema or unknown-tool errors); "
  "`no_result`.")
W("- Bash attribution: each command is split on `&&`, `||`, `|`, `;`, and newlines (quotes and "
  "parentheses respected, heredoc bodies dropped). Wrappers are stripped (`cd`, env assignments, "
  "`env`, `timeout`, `command`, `sudo`, `nohup`, `time`, `nice`, `exec`). The failing segment is picked "
  "in this order: `name-match` (`command not found: X`), `exit-semantics` (the program's known exit "
  "codes fit the observed code), `output-mention` (the program is named in the output), then position "
  "(last non-trivial segment, skipping `head`/`tail`/`tee`/`wc`/`sort`/`cat`-style tails). Only "
  "`high` and `medium` confidence attributions can yield an `expected_nonzero` label. Position-only "
  "(`low`) attributions with exit 1 stay real failures under `unexplained nonzero exit`.")
W("")

# ------------------------------------------------------------ table 1
W("## 1. Failure rate per tool")
W("")
W("Real-failure rate = real failures / calls with a result. MCP tools are grouped by server.")
W("")
W("| Tool | Calls | Real failures | Real-failure rate | Expected non-zero | Denied | Interrupted | Of which tool misuse | Naive errors | Naive rate |")
W("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
agg = collections.defaultdict(collections.Counter)
for r in rows:
    k = tool_key(r)
    agg[k]["calls"] += 1
    if r["category"] == "no_result":
        agg[k]["no_result"] += 1
        continue
    agg[k]["resolved"] += 1
    agg[k][r["category"]] += 1
    if r["subcat"] == "tool_misuse":
        agg[k]["misuse"] += 1
    if is_naive_error(r):
        agg[k]["naive"] += 1
for k, c in sorted(agg.items(), key=lambda kv: (-kv[1]["calls"], kv[0])):
    if c["calls"] < 1:
        continue
    res = c["resolved"]
    W("| %s | %d | %d | %s | %d | %d | %d | %d | %d | %s |" % (
        k, c["calls"], c["real_failure"], pct(c["real_failure"], res), c["expected_nonzero"],
        c["denied"], c["interrupted"], c["misuse"], c["naive"], pct(c["naive"], res)))
W("")
W("Tools with at least one real failure, by count of real failures:")
W("")
for k, c in sorted(agg.items(), key=lambda kv: -kv[1]["real_failure"]):
    if c["real_failure"]:
        W("- `%s`: %d of %d" % (k, c["real_failure"], c["resolved"]))
W("")

# ------------------------------------------------------------ table 2: Bash breakdown
bash = [r for r in rows if r["tool"] == "Bash"]
W("## 2. Bash outcome breakdown")
W("")
W("| Outcome | Main | Subagent | Total | Share of resolved Bash |")
W("|---|---:|---:|---:|---:|")
bc = collections.Counter()
for r in bash:
    bc[(r["category"], r["subcat"] if r["category"] in ("denied", "expected_nonzero", "interrupted") else "", r["tag"])] += 1
bash_res = sum(v for (cat, _, _), v in bc.items() if cat != "no_result")
seen = []
for (cat, sub, tag), _ in bc.items():
    if (cat, sub) not in seen:
        seen.append((cat, sub))
label_order = {"ok": 0, "expected_nonzero": 1, "real_failure": 2, "denied": 3, "interrupted": 4, "tool_misuse": 5, "no_result": 6}
for cat, sub in sorted(seen, key=lambda x: (label_order.get(x[0], 9), x[1])):
    m = bc[(cat, sub, "main")]
    s = bc[(cat, sub, "subagent")]
    t = m + s
    share = pct(t, bash_res) if cat != "no_result" else "-"
    name = cat + ("/" + sub if sub else "")
    W("| %s | %d | %d | %d | %s |" % (name, m, s, t, share))
tot_main = sum(bc[k] for k in bc if k[2] == "main")
tot_sub = sum(bc[k] for k in bc if k[2] == "subagent")
W("| **all** | %d | %d | %d | |" % (tot_main, tot_sub, tot_main + tot_sub))
W("")
bash_real = [r for r in bash if r["category"] == "real_failure"]
bash_naive = [r for r in bash if r["category"] != "no_result" and is_naive_error(r)]
W("Bash: %d resolved calls. Naive errors (is_error or non-zero exit): %d (%s). Real failures: %d (%s). "
  "The difference is expected non-zero exits, denials, and interruptions."
  % (bash_res, len(bash_naive), pct(len(bash_naive), bash_res), len(bash_real), pct(len(bash_real), bash_res)))
W("")
W("Attribution confidence across all Bash calls: " + ", ".join(
    "%s/%s: %d" % (m, c, n) for (m, c), n in collections.Counter(
        (r["method"], r["confidence"]) for r in bash).most_common()) + ".")
W("")

# ------------------------------------------------------------ table 3: expected
W("## 3. Expected non-zero exits (not counted as failures)")
W("")
W("| Subcategory | Count | Example command label |")
W("|---|---:|---|")
ex = collections.defaultdict(collections.Counter)
for r in rows:
    if r["category"] == "expected_nonzero":
        ex[(r["subcat"], r["cluster"])][r["label"]] += 1
for (sub, cl), labels in sorted(ex.items(), key=lambda kv: -sum(kv[1].values())):
    n = sum(labels.values())
    W("| %s (%s) | %d | %s |" % (cl, sub, n, ", ".join("`%s`" % l for l, _ in labels.most_common(3))))
W("")

# ------------------------------------------------------------ table 4: denied
W("## 4. Denied and interrupted calls (not counted as failures)")
W("")
W("| Source | Subtype | Count | Notes |")
W("|---|---|---:|---|")
dn = collections.Counter()
dn_notes = {}
for r in rows:
    if r["category"] in ("denied", "interrupted"):
        key = (r["category"], r["subcat"], r["tool"] == "Bash")
        dn[key] += 1
        if r["category"] == "denied" and r["subcat"] == "classifier":
            dn_notes.setdefault(key, collections.Counter())[r["cluster"]] += 1
for (cat, sub, is_b), n in sorted(dn.items(), key=lambda kv: -kv[1]):
    note = ""
    if (cat, sub, is_b) in dn_notes:
        note = "reasons: " + ", ".join("%s %d" % (k, v) for k, v in dn_notes[(cat, sub, is_b)].most_common())
    W("| %s | %s | %d | %s |" % ("Bash" if is_b else "other tool", cat + "/" + sub, n, note))
W("")
hook_msgs = collections.Counter()
for r in rows:
    if r["category"] == "denied" and r["subcat"] == "hook":
        hook_msgs[re.sub(r"\s+", " ", r["output_head"])[:140]] += 1
if hook_msgs:
    W("Hook messages (redacted, first 140 characters):")
    W("")
    for m, n in hook_msgs.most_common():
        W("- %d x `%s`" % (n, m))
    W("")

# ------------------------------------------------------------ table 5: clusters
W("## 5. Real failures by cause")
W("")
clusters = collections.defaultdict(list)
for r in rows:
    if r["category"] == "real_failure":
        clusters[("Bash" if r["tool"] == "Bash" else "other: " + r["tool"])].append(r)
W("| Cluster | Tool | Count | Example command label | Example output (redacted, 150 chars) |")
W("|---|---|---:|---|---|")
by_cluster = collections.defaultdict(list)
for r in rows:
    if r["category"] == "real_failure":
        by_cluster[(r["cluster"], "Bash" if r["tool"] == "Bash" else r["tool"])].append(r)
for (cl, tool), rs in sorted(by_cluster.items(), key=lambda kv: -len(kv[1])):
    labels = collections.Counter(x["label"] for x in rs).most_common(2)
    ex_out = ""
    for x in rs:
        o = re.sub(r"\s+", " ", x["output_head"] or "")
        o = re.sub(r"^Exit code \d+ ?", "", o).strip()
        if o:
            ex_out = o[:150].replace("|", "\\|")
            break
    W("| %s | %s | %d | %s | `%s` |" % (cl, tool, len(rs), ", ".join("`%s` (%d)" % (l, n) for l, n in labels),
                                       ex_out))
W("")

# ------------------------------------------------------------ table 6: top 20 program+subcommand
W("## 6. Top 20 program and subcommand by real failures")
W("")
W("Label is the attributed segment (see method). Rate = real failures / calls with a result for that label.")
W("")
W("| # | Program / subcommand | Calls | Real failures | Real-failure rate | Dominant cause (count) |")
W("|---:|---|---:|---:|---:|---|")
lab = collections.defaultdict(collections.Counter)
labcause = collections.defaultdict(collections.Counter)
for r in bash:
    L = r["label"] or "(empty)"
    if r["category"] == "no_result":
        lab[L]["calls"] += 0
        lab[L]["noresult"] += 1
        continue
    lab[L]["resolved"] += 1
    lab[L]["calls"] += 1
    if r["category"] == "real_failure":
        lab[L]["real"] += 1
        labcause[L][r["cluster"]] += 1
top = sorted(((L, c) for L, c in lab.items() if c["real"]), key=lambda kv: (-kv[1]["real"], -kv[1]["resolved"]))
for i, (L, c) in enumerate(top[:20], 1):
    cause = labcause[L].most_common(1)[0]
    W("| %d | `%s` | %d | %d | %s | %s (%d) |" % (i, L, c["resolved"], c["real"], pct(c["real"], c["resolved"]),
                                              cause[0], cause[1]))
W("")
W("Labels with the most calls, for context (resolved calls, real failures):")
W("")
for L, c in sorted(lab.items(), key=lambda kv: -kv[1]["resolved"])[:15]:
    W("- `%s`: %d calls, %d real failures (%s)" % (L, c["resolved"], c["real"], pct(c["real"], c["resolved"])))
W("")

# ------------------------------------------------------------ table 7: self kill detail
sk = [r for r in rows if r["cluster"].startswith("killed by pkill")]
if sk:
    W("## 7. pkill/kill exits (detail)")
    W("")
    W("%d calls exited with 144, 137, 143, or 9 and contain `pkill`, `killall`, or `kill`. "
      "These commands ran `pkill -f PATTERN` in the same shell whose command line contains PATTERN, "
      "so the shell killed itself. Example commands (redacted, 160 chars):" % len(sk))
    W("")
    for r in sk[:4]:
        W("- `%s`" % re.sub(r"\s+", " ", r["full_command"])[:160].replace("`", "'"))
    W("")

# ------------------------------------------------------------ table 8: masked test failures
mt = [r for r in bash if r.get("masked_test_failure")]
tl = [r for r in bash if r.get("test_like")]
W("## 8. Test failures hidden by the exit status (not counted above)")
W("")
W("Candidates: test-runner calls whose output carries a runner or bazel summary line naming failing tests, "
  "but whose tool result shows no non-zero exit. The regex is strict, but a script that prints earlier test output can still match, "
  "so the list below needs a manual check. "
  "The usual cause is a pipe such as `| tail -n 20`, which replaces the test runner's exit status with "
  "the status of `tail`. Count: %d of %d test-runner Bash calls, of which %d contain a pipe." % (
      len(mt), len(tl), sum(1 for r in mt if r.get("piped"))))
W("")
for r in mt[:5]:
    W("- %s, `%s`" % (r["ts"][:10], re.sub(r"\s+", " ", r["full_command"])[:120].replace("`", "'")))
W("")

with open(os.path.join(OUT, "report_tables.md"), "w") as fh:
    fh.write("\n".join(out) + "\n")
print("wrote", os.path.join(OUT, "report_tables.md"), len(out), "lines")
